def sha256_of(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def s3_list(prefix, delimiter=None, max_keys=1000):
    params = {"list-type": "2", "prefix": prefix, "max-keys": max_keys}
    if delimiter:
        params["delimiter"] = delimiter
    url = S3 + "?" + urllib.parse.urlencode(params)
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
    with urllib.request.urlopen(req, timeout=90) as fh:
        body = fh.read().decode()
    keys = []
    for line in body.split("<Contents>")[1:]:
        k = line.split("<Key>")[1].split("</Key>")[0]
        n = int(line.split("<Size>")[1].split("</Size>")[0])
        keys.append((k, n))
    return keys


def fetch_plate(key, dest):
    if os.path.exists(dest) and os.path.getsize(dest) > 0:
        return dest, "exists", os.path.getsize(dest)
    url = S3 + urllib.parse.quote(key)
    try:
        req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
        with urllib.request.urlopen(req, timeout=180) as r:
            declared = int(r.headers.get("Content-Length", "-1"))
            tmp = dest + ".part"
            os.makedirs(os.path.dirname(dest), exist_ok=True)
            blob = r.read()
            with open(tmp, "wb") as f:
                f.write(blob)
        os.replace(tmp, dest)
        got = os.path.getsize(dest)
        if declared >= 0 and got != declared:
            return dest, f"TRUNCATED {got}!={declared}", got
        return dest, "ok", got
    except Exception as e:
        return dest, f"FAIL:{type(e).__name__}:{str(e)[:120]}", 0


def stage_fetch(args):
    os.makedirs(EXT, exist_ok=True)
    plates = [k.split("/")[-2] for k, _ in s3_list(BATCH) if k.endswith("/load_data.csv")]
    plates = sorted(plates)[:args.plates]
    jobs = [(BATCH + p + "/load_data.csv", os.path.join(EXT, f"{p}.csv")) for p in plates]
    print(f"batch {BATCH}\n{len(plates)} plates selected: {plates}", flush=True)
    rows = []
    with ThreadPoolExecutor(max_workers=args.workers) as ex:
        futs = {ex.submit(fetch_plate, k, d): (k, d) for k, d in jobs}
        for fut in as_completed(futs):
            key, dest = futs[fut]
            d, status, n = fut.result()
            print(f"  {os.path.basename(dest):22s} {status:32s} {n/1e6:7.2f} MB", flush=True)
            rows.append({"s3_key": key, "local_path": d, "bytes": n, "status": status,
                         "sha256": sha256_of(d) if status in ("ok", "exists") and n else ""})
    total = sum(r["bytes"] for r in rows if r["status"] in ("ok", "exists"))
    print(f"\ndownloaded total {total/1e6:.1f} MB (budget {BUDGET_BYTES/1e6:.0f} MB)", flush=True)
    old = []
    if os.path.exists(MANIFEST):
        with open(MANIFEST, newline="") as f:
            old = list(csv.DictReader(f))
    seen = {r["local_path"]: r for r in old}
    seen.update({r["local_path"]: r for r in rows})
    with open(MANIFEST, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["s3_key", "local_path", "bytes", "status", "sha256"])
        w.writeheader()
        for r in sorted(seen.values(), key=lambda x: x["s3_key"]):
            w.writerow(r)
    print(f"manifest ({len(seen)} rows, sha256 per file) -> {MANIFEST}", flush=True)
    bad = [r for r in rows if r["status"] not in ("ok", "exists")]
    if bad:
        print(f"!! {len(bad)} plate(s) did NOT download cleanly - those are unverified, "
              f"not silently dropped: {[(os.path.basename(b['local_path']), b['status']) for b in bad]}")
        return 2
    return 0


class HttpRangeFile:
    """Minimal seekable HTTPS reader (Range requests), so parquet footers can be read
    without aiohttp/s3fs and without transferring the body. Only `read`/`seek`/`tell`
    are needed by pyarrow.ParquetFile."""

    def __init__(self, url, chunk=8 * 1024 * 1024):
        self.url, self.chunk, self.pos, self.closed = url, chunk, 0, False
        req = urllib.request.Request(url, method="HEAD",
                                     headers={"User-Agent": "Mozilla/5.0"})
        with urllib.request.urlopen(req, timeout=60) as r:
            self.size = int(r.headers["Content-Length"])
            self.accept_ranges = (r.headers.get("Accept-Ranges") or "").lower()

    def readable(self):
        return True

    def seekable(self):
        return True

    def seek(self, offset, whence=0):
        self.pos = {0: offset, 1: self.pos + offset, 2: self.size + offset}[whence]
        return self.pos

    def tell(self):
        return self.pos

    def read(self, n=-1):
        if n is None or n < 0:
            n = self.size - self.pos
        n = min(n, max(0, self.size - self.pos))
        if n == 0:
            return b""
        start, end = self.pos, self.pos + n - 1
        req = urllib.request.Request(self.url, headers={"User-Agent": "Mozilla/5.0",
                                                       "Range": f"bytes={start}-{end}"})
        with urllib.request.urlopen(req, timeout=180) as r:
            blob = r.read()
        if len(blob) != n:
            raise IOError(f"range {start}-{end} returned {len(blob)} of {n} bytes")
        self.pos += len(blob)
        return blob

    def close(self):
        self.closed = True

    @property
    def mode(self):
        return "rb"


def stage_schema(args):
    """Remote schema probe: read only the parquet footers through HTTP range requests.

    Nothing is written to disk here. The point is to find out *before* spending the
    download budget whether the per-image profile table even carries compound identity,
    and whether its column names share the Cells_/Cytoplasm_/Nuclei_ vocabulary that the
    classifier uses.
    """
    import pyarrow.parquet as pq

    keys = args.keys.split(",") if args.keys else DEFAULT_SCHEMA_KEYS
    out = {}
    for key in keys:
        url = S3 + urllib.parse.quote(key)
        short = key.split("/")[-1]
        try:
            fh = HttpRangeFile(url)
            pf = pq.ParquetFile(fh)
            names = pf.schema_arrow.names
            rows = pf.metadata.num_rows
            groups = pf.metadata.num_row_groups
        except Exception as e:
            print(f"  {short:45s} SCHEMA FAILED {type(e).__name__}: {str(e)[:150]}")
            out[short] = {"error": f"{type(e).__name__}: {str(e)[:200]}"}
            continue
        pref = {}
        for n in names:
            p = n.split("_")[0]
            pref[p] = pref.get(p, 0) + 1
        out[short] = {"key": key, "rows": rows, "cols": len(names), "row_groups": groups,
                      "prefix_counts": pref,
                      "metadata_cols": [n for n in names if n.startswith("Metadata_")],
                      "url_cols": [n for n in names if n.startswith("URL_")],
                      "n_features_cells_nuclei_cyto":
                          sum(1 for n in names if n.startswith(FEAT_PREFIX))}
        print(f"  {short:45s} rows={rows:7d} cols={len(names):5d} groups={groups:3d} "
              f"| Cells/Nuclei/Cytoplasm cols={out[short]['n_features_cells_nuclei_cyto']:5d}")
        print(f"      Metadata_: {out[short]['metadata_cols'][:16]}")
    dest = os.path.join(REPORTS, "21_stage12_p1_external_site_schema.json")
    with open(dest, "w", encoding="utf-8") as f:
        json.dump(out, f, indent=1, ensure_ascii=False)
    print(f"\nwrote {dest}")
    return 0


def load_well_table(path):
    """Per-plate load_data.csv -> per-well median of every feature, metadata kept."""
    df = pd.read_csv(path)
    meta = [c for c in df.columns if c.startswith("Metadata_")]
    img = [c for c in df.columns if c.startswith("Image_")]
    obj = [c for c in df.columns if c.startswith(("Cells_", "Cytoplasm_", "Nuclei_",
                                                  "Mito_", "ER_", "AGP_", "Phalloidin_",
                                                  "Brightfield_", "YL_"))]
    keys = ["Metadata_Plate", "Metadata_Well"]
    well = df.groupby(keys, sort=True)[obj].median()
    keep = [c for c in meta if c not in well.columns]
    first = df.groupby(keys, sort=True)[keep].first() if keep else None
    out = well.join(first) if first is not None else well
    return df, out, {"n_meta": len(meta), "n_image": len(img), "n_obj": len(obj)}


def stage_inspect(args):
    files = sorted(f for f in os.listdir(EXT)
                   if f.endswith(".csv") and not f.startswith("manifest_"))
    if not files:
        print("nothing fetched yet - run --stage fetch first"); return 1
    manifest = {}
    with open(MANIFEST, newline="") as f:
        for r in csv.DictReader(f):
            manifest[os.path.basename(r["local_path"])] = r
    print(f"{len(files)} plate file(s), manifest rows {len(manifest)}\n")
    info = {}
    for i, name in enumerate(files[:args.plates]):
        path = os.path.join(EXT, name)
        m = manifest.get(name, {})
        recomputed = sha256_of(path)
        ok = (m.get("sha256") == recomputed)
        df, well, cnt = load_well_table(path)
        if i == 0:
            info["columns_sample"] = list(df.columns)[:60]
            info["n_cols"] = int(df.columns.size)
            info["meta_cols"] = [c for c in df.columns if c.startswith("Metadata_")]
            info["prefixes"] = sorted({c.split("_")[0] for c in df.columns})
            for col in ("Metadata_cell_line", "Metadata_Location", "Metadata_controls",
                        "Metadata_control_type", "Metadata_solvent", "Metadata_inchikey",
                        "Metadata_InChIKey", "Metadata_broad_sample", "Metadata_compound"):
                if col in df.columns:
                    info.setdefault("value_counts", {})[col] = {
                        str(k): int(v) for k, v in df[col].astype(str).value_counts().head(8).items()}
        print(f"--- {name}: sha256 match={ok} rows={len(df)} cols={df.columns.size} "
              f"meta={cnt['n_meta']} obj={cnt['n_obj']} wells={len(well)}  "
              f"bytes={m.get('bytes')}")
    if args.show_columns:
        print("\nMetadata_ columns:", info["meta_cols"])
        print("\nprefixes:", info["prefixes"])
        print("\nvalue counts:")
        print(json.dumps(info.get("value_counts", {}), indent=1)[:3000])
    out = os.path.join(REPORTS, "21_stage12_p1_external_site_inspect.json")
    with open(out, "w", encoding="utf-8") as f:
        json.dump(info, f, indent=1, ensure_ascii=False)
    print(f"\nwrote {out}")
    return 0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--stage", choices=["fetch", "inspect", "schema"], default="fetch")
    ap.add_argument("--plates", type=int, default=2)
