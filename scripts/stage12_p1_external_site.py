"""Stage 12 P1 - external *site* validation: fetch and inspect one CPG dataset that was
not generated by the lab that produced our training plates.

Context. Everything the project validated so far (stage11_p3) lives inside one derivation
of one dataset: `cpg0000-jump-pilot/source_4`, plates BR00116991/BR00116992 - same lab,
same instrument, same CellProfiler run, same normalization. That is a cross-*plate* check,
not a cross-*source* check, and the repo says so in its own docstring
("Uses ONLY already-downloaded data (zero new downloads)").

This stage pulls per-plate CellProfiler output from `cpg0016-jump` (the JUMP Cell Painting
compendium, acquired and processed independently of pilot source_4) and answers the three
questions that have to be settled before any classifier can be transferred:

  1. schema   - do the feature column names overlap the 904-feature pilot set at all,
                and specifically the Cells_/Cytoplasm_/Nuclei_ prefix the classifier uses?
  2. assay    - which cell line / channel set, and are there DMSO negative-control wells
                to run the same robust-z recipe against?
  3. compounds- do the InChIKeys intersect JUMP-Target-1? without overlap there is no
                same-compound transfer test to run.

Every downloaded file is hashed (SHA256) and recorded in a manifest *before* any modelling
happens, together with the byte count returned by S3, so the external data set is auditable
and a truncated download cannot silently become "training data".

Usage:
    python scripts/stage12_p1_external_site.py --stage fetch --plates 2
    python scripts/stage12_p1_external_site.py --stage inspect
"""
