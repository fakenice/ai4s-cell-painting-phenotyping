#!/usr/bin/env python
"""Rebuild docs/12_technical_report_draft_v7.pdf from reports/12_technical_report_draft_v7.md.

Route (same as the ad-hoc Stage 9-11 builds, now scripted so it does not drift):
  pandoc <md> -> standalone HTML (docs/print_style.css, embedded resources)
  Chrome headless --print-to-pdf -> docs/12_technical_report_draft_v7.pdf

Usage (from the repo root or anywhere; paths are resolved relative to this file):
    python scripts/build_report_pdf.py
    python scripts/build_report_pdf.py --check-only      # verify the existing PDF only

Verification performed after each build (printed, and non-zero exit on failure):
  * page count and MD5 of the produced PDF
  * required text-layer anchors present (headline numbers / section headings)
  * forbidden generated-content disclaimers absent from the text layer
Nothing outside docs/ is written except the throw-away HTML under build/pdf/.
"""
import argparse
import hashlib
import os
import shutil
import subprocess
import sys
import tempfile

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MD = os.path.join(REPO, "reports", "12_technical_report_draft_v7.md")
CSS = os.path.join(REPO, "docs", "print_style.css")
OUT = os.path.join(REPO, "docs", "12_technical_report_draft_v7.pdf")
BUILD = os.path.join(REPO, "build", "pdf")

CHROME_CANDIDATES = [
    r"C:\Program Files\Google\Chrome\Application\chrome.exe",
    r"C:\Program Files (x86)\Google\Chrome\Application\chrome.exe",
    r"C:\Program Files (x86)\Microsoft\Edge\Application\msedge.exe",
    r"C:\Program Files\Microsoft\Edge\Application\msedge.exe",
]

# Text-layer anchors: each must appear in the rebuilt PDF. Kept to strings that
# are stable section headings / committed headline numbers, so the check fails if
# a section is silently dropped by a bad build.
REQUIRED = [
    "Category Declaration",
    "Table of Contents",
    "2. Data & Materials",
    "4. Results",
    "External validation on an independent site",
    "position-decoupled",
    "0.5971",
    "not reproduced",
    "5. Discussion",
    "8. Conclusion",
    "AI Use Disclosure",
    "References",
]

FORBIDDEN = [
    "A I-generated",
    "AI-generated content",
    "generated by an AI",
    "chatbot",
    "大模型生成",
    "AI 生成",
]


def md5(path):
    with open(path, "rb") as f:
        return hashlib.md5(f.read()).hexdigest()


def find_browser():
    for c in CHROME_CANDIDATES:
        if os.path.exists(c):
            return c
    raise SystemExit("no Chrome/Edge binary found at the usual Windows install paths")


def page_count(path):
    """Page count + text layer, via PyMuPDF when installed, else the /Type /Page tally."""
    try:
        import pymupdf  # type: ignore
    except ImportError:
        try:
            import fitz as pymupdf  # type: ignore
        except ImportError:
            with open(path, "rb") as f:
                data = f.read()
            return data.count(b"/Type /Page") - data.count(b"/Type /Pages"), None
    doc = pymupdf.open(path)
    try:
        return doc.page_count, "".join(p.get_text() for p in doc)
    finally:
        doc.close()


def run(cmd, **kw):
    print("+ " + " ".join(f'"{c}"' if " " in c else c for c in cmd[:6]) + " ...")
    return subprocess.run(cmd, check=True, **kw)


def build(keep_html=False):
    if not os.path.exists(MD):
        raise SystemExit("missing report source: " + MD)
    if not os.path.exists(CSS):
        raise SystemExit("missing print style: " + CSS)
    shutilwhich = shutil.which("pandoc")
    if not shutilwhich:
        raise SystemExit("pandoc not on PATH")
    os.makedirs(BUILD, exist_ok=True)
    html = os.path.join(BUILD, "12_technical_report_draft_v7.html")
    pandoc = [
        shutilwhich, MD,
        "-f", "markdown+pipe_tables+yaml_metadata_block",
        "-t", "html5", "--standalone", "--embed-resources",
        "--metadata", "title=Technical Report v7 (JUMP-Cell Painting morphological profiling)",
        "--css", CSS,
        "--resource-path", os.pathsep.join([os.path.dirname(MD), REPO, os.path.join(REPO, "reports")]),
        "-o", html,
    ]
    run(pandoc)
    print(f"html: {os.path.getsize(html):,} bytes")

    browser = find_browser()
    tmp_out = os.path.join(tempfile.gettempdir() if False else BUILD,
                           "12_technical_report_draft_v7.pdf")
    if os.path.exists(tmp_out):
        os.remove(tmp_out)
    url = "file:///" + html.replace("\\", "/").lstrip("/")
    run([
        browser, "--headless=new", "--disable-gpu", "--no-sandbox",
        "--no-pdf-header-footer", "--virtual-time-budget=90000",
        "--run-all-compositor-stages-before-draw",
        f"--print-to-pdf={tmp_out}", url,
    ], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    size = os.path.getsize(tmp_out)
    if size < 50_000:
        raise SystemExit(f"suspiciously small PDF ({size} bytes) - build aborted, "
                         "docs/ left untouched")
    shutil.copyfile(tmp_out, OUT)
    print(f"pdf : {size:,} bytes -> {os.path.relpath(OUT, REPO)}")
    if not keep_html:
        os.remove(html)
        os.remove(tmp_out)
    return OUT


def verify(path=OUT):
    n, text = page_count(path)
    digest = md5(path)
    print(f"\nverify {os.path.relpath(path, REPO)}: pages={n} md5={digest} "
          f"bytes={os.path.getsize(path):,}")
    ok = True
    if text is None:
        print("  text layer: PyMuPDF unavailable - anchor check skipped")
        return ok, n, digest
    missing = [s for s in REQUIRED if s not in text]
    hits = [s for s in FORBIDDEN if s in text]
    for s in REQUIRED:
        print(f"  required {'OK  ' if s not in missing else 'MISS'}  {s!r}")
    for s in hits:
        print(f"  FORBIDDEN HIT  {s!r}")
    ok = not missing and not hits
    return ok, n, digest


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check-only", action="store_true",
                    help="verify the existing PDF without rebuilding")
    ap.add_argument("--keep-html", action="store_true",
                    help="keep the intermediate HTML under build/pdf/")
    a = ap.parse_args()
    if not a.check_only:
        build(keep_html=a.keep_html)
    ok, n, digest = verify()
    if not ok:
        print("\nFAIL - see missing/forbidden text-layer items above", file=sys.stderr)
        return 1
    print(f"\nPASS - {n} pages, md5 {digest}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
